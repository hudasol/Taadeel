"""Generate docs/VALIDATION_UK.md and the README results block from result files. Never edit by hand."""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
R = ROOT / "results"
START, END = "<!-- RESULTS:START (generated by taadeel.report, do not edit) -->", "<!-- RESULTS:END -->"


def pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def build() -> tuple[str, str]:
    uk = json.loads((R / "uk_validation.json").read_text())
    am = json.loads((R / "uk_amending.json").read_text())
    ho = json.loads((R / "heldout_synthetic.json").read_text())
    ag = uk["aggregate"]
    al, cl = ag["alignment_one_day"], ag["classes_one_day"]
    pit, rec, ev, rv = ag["point_in_time"], ag["recorded_effects"], ag["engine_vs_recorded_effects"], ag["renumbering_variant"]

    head = (f"**Held-out synthetic (clean, run once): {ho['hits']} of {ho['total']} point predictions hit.** "
            f"**Real UK data (English, England and Wales view only): alignment {pct(al['accuracy'])} "
            f"({al['correct']} of {al['shared_sections']} sections), point in time {pct(pit['accuracy'])} "
            f"({pit['correct']} of {pit['queries']} queries).** UAE law: unvalidated.")

    L = ["# UK real data validation (generated)", "",
         "Generated by `python -m taadeel.report` from `results/uk_validation.json` and `results/uk_amending.json`. Do not edit by hand.",
         "Contains public sector information licensed under the Open Government Licence v3.0.", "",
         "**Scope: this validates the locked engine on English UK Public General Acts (England and Wales view, body sections). "
         "It says nothing about UAE law, Arabic text or UAE drafting.** The engine files were not modified or tuned for it. "
         "Ground truth is editorial (legislation.gov.uk revised versions and effects), not a legal original, and the hand check was done by the AI agent, not by a lawyer.", "",
         "## Headline", "", head, "",
         "## Alignment and diff classification (one day windows)", "",
         f"Pairs: the snapshot on the day before each recorded effect date against the snapshot on that date. Truth: same section id means same section; text differs means replaced. "
         f"The engine never sees section ids.", "",
         f"Alignment: {al['correct']} correct of {al['shared_sections']} shared sections ({pct(al['accuracy'])}); wrong {al['wrong']}; unmatched {al['unmatched']}; false matches {al['false_matches']}; low confidence pairs {al['low_confidence_pairs']}.", "",
         "| class | TP | FP | FN | precision | recall |", "|---|---|---|---|---|---|"]
    for c, d in cl.items():
        L.append(f"| {c} | {d['tp']} | {d['fp']} | {d['fn']} | {pct(d['precision'])} | {pct(d['recall'])} |")
    L += ["", "One day windows change little text, so these are easy cases. Long gap pairs (first to latest snapshot) per Act are below.", "",
          "## Per Act", "", "| Act | one day windows | long gap: shared | long gap: correct | long gap: low confidence | long gap class counts (TP/FP/FN) |", "|---|---|---|---|---|---|"]
    for a in uk["acts"]:
        lg = a["long_gap"]
        if lg:
            cc = "; ".join(f"{k} {v.get('tp',0)}/{v.get('fp',0)}/{v.get('fn',0)}" for k, v in sorted(lg["classes"].items()))
            L.append(f"| {a['act']} | {a['windows']} | {lg['shared']} | {lg['correct']} | {lg['low_conf_pairs']} | {cc} |")
    L += ["", "## Recorded effects against snapshots and against the engine", "",
          f"Effects checked (dated, usable, England and Wales): {rec['effects_checked']}. Snapshot shows a change at the named section on that date: {rec['effects_with_snapshot_change']} ({pct(rec['effects_with_snapshot_change']/rec['effects_checked'])}); class agrees in {rec['effects_class_agrees']}.",
          f"Snapshot changes in the windows: {rec['snapshot_changes']}; with a recorded dated effect: {rec['snapshot_changes_with_effect']} ({pct(rec['snapshot_changes_with_effect']/rec['snapshot_changes'])}). The rest are changes the usable dated effects do not explain (undated, ambiguous, prospective or lagging effects).",
          f"Engine against recorded effects (section level, class must agree): TP {ev['tp']}, FN {ev['fn']}, FP {ev['fp']}. These disagreements mostly reflect the effects data, not the engine, because the engine matched the snapshots exactly.", "",
          "## Point in time", "",
          f"A timeline is built from the base snapshot plus one version per recorded effect date; for each date D the engine is asked for D minus one day and D, and the text served is compared with an independently fetched snapshot. Correct {pit['correct']} of {pit['queries']} ({pct(pit['accuracy'])}); wrong {pit['wrong']}. "
          "Every failure is a case where the site's snapshot on D minus one day differs from the previous recorded effect version, so a change took effect on a date the recorded effects did not give. "
          "This is a real limit of building a timeline from effects alone.", "",
          "| Act | queries | correct | wrong |", "|---|---|---|---|"]
    for p in uk["point_in_time"]:
        L.append(f"| {p['act']} | {p.get('queries',0)} | {p.get('correct',0)} | {p.get('wrong',0)} |")
    L += ["", "## Renumbering variant (real text, synthetic renumbering)", "",
          f"UK drafting rarely renumbers, so a labelled variant inserts a section and shifts later numbers by one: {rv['correct']} of {rv['sections']} sections aligned correctly ({pct(rv['accuracy'])}) across {rv['runs']} runs; the inserted section was found {rv['inserted_detected']} of {rv['runs']} times. This text is real but the renumbering is synthetic.", "",
          "## English amendment by reference patterns", "",
          f"Sample: {am['fetched']} amending Act sections fetched, {am['instruction_bearing']} contain amendment keywords. Split by SHA-1 parity of the URL into dev and test. Patterns were extended after reading the dev half only; the test half was measured once per pattern set. Truth: recorded effects naming the amending section. Very small sample, effects from the same section are correlated, treat as indicative.", "",
          "| split | patterns | sections | effects | found | recall | parsed instructions | matching a recorded effect (precision lower bound) |", "|---|---|---|---|---|---|---|---|"]
    for part in ("dev", "test"):
        for k, lab in (("original_patterns", "original four"), ("extended_patterns", "extended")):
            d = am[part][k]
            L.append(f"| {part} | {lab} | {d['sections']} | {d['recorded_effects']} | {d['effects_found']} | {pct(d['recall'])} | {d['parsed_instructions']} | {d['instructions_matching_a_recorded_effect']} ({pct(d['precision_lower_bound'])}) |")
    L += ["", "The Arabic lexicon (`amend_ar.py`) has no real text to be measured against and is **unvalidated on real UAE text**.", "",
          "## Defects found during validation (disclosed)", "",
          "The first full run and a hand check of a sample of recorded effects exposed three defects in the effects reader (`clml.py`), not in the locked engine. They were fixed and the evaluation re-run; the earlier result files are kept as `results/uk_validation_run1.json`, `run2` and `run3`.",
          "1. A subsection effect such as `S. 14(2) repealed` was read as a whole section repeal.",
          "2. A date such as `1.10.2007 for S. and 1.10.2008 otherwise` was resolved to the second date; the meaning of `S.` is not in the retrieved terms, so such dates are now ambiguous and excluded.",
          "3. Northern Ireland only versions of a section with the same id were not dropped, giving duplicate section ids in three snapshots (the evaluator silently overwrote them). Duplicates now raise an error.", "",
          "## Known limits", "",
          "* Some recorded effects show no snapshot change on their date (for example Theft Act 1968 s. 12A and s. 24A insertions, and Misuse of Drugs Act 1971 insertions dated 1 July 1991). The cause was not established; one possibility, not tested, is that the site does not create a version at every effect date.",
          "* Schedules are out of scope. Devolved material is out of scope. Prospective changes are excluded.",
          "* Hand check by the AI agent, not a lawyer: a seeded sample (seed 20261012) of 20 disagreeing and 10 agreeing effects, then every remaining disagreement after the fixes, was read against the section text and the effect wording. All 10 sampled agreeing effects matched their wording. The unexplained cases above remain.", ""]
    block = "\n".join([START, "", head, "",
                       "Details: [`docs/VALIDATION_UK.md`](docs/VALIDATION_UK.md), [`docs/HELDOUT_RESULTS.md`](docs/HELDOUT_RESULTS.md). "
                       "Real UK numbers validate English UK legislation only. They say nothing about UAE law.", "", END])
    return "\n".join(L), block


def main() -> None:
    doc, block = build()
    (ROOT / "docs" / "VALIDATION_UK.md").write_text(doc, encoding="utf-8")
    rd = ROOT / "README.md"
    t = rd.read_text(encoding="utf-8")
    if START in t:
        t = re.sub(re.escape(START) + r".*?" + re.escape(END), block, t, flags=re.S)
    else:
        t = t.replace("## Status", block + "\n\n## Status", 1)
    rd.write_text(t, encoding="utf-8")


if __name__ == "__main__":
    main()
