"""Search and corpus endpoints. Not legal advice.

Mount with ``app.include_router(search_api.router)``. Override the data source with
``search_api.set_store(store)``, by monkeypatching ``search_api.get_store``, or via
``app.dependency_overrides[search_api.store_dependency]``.
"""
from __future__ import annotations

from fastapi import APIRouter, Depends, Query
from fastapi.responses import JSONResponse

from .store import CORPORA, DISCLAIMER, Store, build_demo_store, resolve_corpora

router = APIRouter()
_STORE: Store | None = None

CORPUS_INFO = {
    "uae": {
        "label_ar": "التشريعات الإماراتية", "label_en": "UAE legislation",
        "licence": None, "attribution": None, "synthetic": False,
        "note": "No real UAE legislation is loaded: no source currently permits collection (see docs/DATA_SOURCES.md).",
    },
    "uk-validation": {
        "label_ar": "مجموعة التحقق البريطانية (إنجليزية، ليست قانونًا إماراتيًا)",
        "label_en": "UK validation corpus (English, not UAE law)",
        "licence": "Open Government Licence v3.0",
        "attribution": "Contains public sector information licensed under the Open Government Licence v3.0 "
                       "(legislation.gov.uk). Used only to validate the engine.",
        "synthetic": False,
        "note": "Real English UK legislation used for engine validation only. It is not UAE law.",
    },
    "synthetic": {
        "label_ar": "بيانات اصطناعية (ليست تشريعًا)", "label_en": "SYNTHETIC test data (not legislation)",
        "licence": "CC0-1.0 (proposed)",
        "attribution": "Generated by taadeel.synthetic: random text with no legal meaning.",
        "synthetic": True,
        "note": "Synthetic test text. It is not legislation and carries no legal meaning.",
    },
}


def get_store() -> Store:
    """Default store provider (demo store). Replace via set_store() or monkeypatching."""
    global _STORE
    if _STORE is None:
        _STORE = build_demo_store()
    return _STORE


def set_store(store: Store | None) -> None:
    global _STORE
    _STORE = store


def store_dependency() -> Store:
    return get_store()          # resolved at call time so overrides of get_store take effect


def _payload(data: dict, synthetic: bool) -> dict:
    return {"disclaimer": DISCLAIMER, "synthetic": synthetic, **data}


@router.get("/api/corpora")
def corpora(store: Store = Depends(store_dependency)) -> dict:
    counts = store.corpus_counts()
    items = [{"corpus": c, **CORPUS_INFO[c], "counts": counts[c]} for c in ("uae", "uk-validation", "synthetic")]
    # top-level 'synthetic' is False: this is a metadata listing; each entry carries its own flag.
    return _payload({"default": "uae", "corpora": items}, synthetic=False)


@router.get("/api/search")
def search(q: str = Query("", max_length=300), corpus: str = "uae", limit: int = Query(20, ge=1, le=100),
           lang: str | None = None, store: Store = Depends(store_dependency)):
    try:
        cs = resolve_corpora(corpus)
    except ValueError:
        return JSONResponse(_payload({"error": f"unknown corpus {corpus!r}",
                                      "allowed": list(CORPORA) + ["real"]}, synthetic=False), status_code=400)
    is_syn = cs == ("synthetic",)
    results = store.search(q, corpus=corpus, limit=limit, lang=lang)
    if corpus == "real":
        note = "Real view: UAE and UK validation corpora (never synthetic)."
    else:
        note = CORPUS_INFO[corpus]["note"]
    if not results and corpus in ("uae", "real") and sum(store.corpus_counts()["uae"].values()) == 0:
        note = CORPUS_INFO["uae"]["note"]
    return _payload({"query": q, "corpus": corpus, "count": len(results), "results": results, "note": note},
                    synthetic=is_syn)
