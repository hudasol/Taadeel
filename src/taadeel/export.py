"""Versioned dataset release (JSONL + data card). Synthetic-only until real data is permitted."""
from __future__ import annotations

import hashlib
import json
import sys
from dataclasses import asdict
from pathlib import Path

from .align import align
from .diff import diff
from .synthetic import make_pair

VERSION = "0.1.0-synthetic"

CARD = """# Taadeel dataset card — {version}

**Synthetic data only. Not legislation. Not legal advice.**

* Contents: `changes.jsonl`, one article-level change per line (kind, aligned article ids, confidence, score, word-level ops, provenance fields). Generated by `taadeel.synthetic` with known ground-truth operations; `synthetic` is `true` on every row.
* Intended use: testing and benchmarking alignment, diffing and temporal logic. Not for any statement about what the law says.
* Not included: any real UAE legislation text. No source currently permits collection (see docs/DATA_SOURCES.md). A real-data release requires written permission and a stated licence from the publisher.
* Generation: seeds 0-{n} (40 articles each), default operation mix; reproducible via `python -m taadeel.export`.
* Known limitations: random word sequences, no legal drafting structure, no cross-references.
* Integrity: sha256 of changes.jsonl = `{sha}`.
* License of this synthetic dataset: CC0-1.0 (proposed; owner to confirm).
"""


def export(out: str | Path, n: int = 20) -> Path:
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    rows = []
    for seed in range(n):
        p = make_pair(seed)
        for c in diff(p.a, p.b, align(p.a, p.b), amending_work_id="synthetic/amend/1"):
            d = asdict(c)
            d.update(synthetic=True, doc_seed=seed, work_id=p.a.work_id,
                     source_url=p.b.source_url, retrieved_at=p.b.retrieved_at)
            rows.append(d)
    f = out / "changes.jsonl"
    f.write_text("\n".join(json.dumps(r, ensure_ascii=False, sort_keys=True) for r in rows) + "\n", encoding="utf-8")
    sha = hashlib.sha256(f.read_bytes()).hexdigest()
    (out / "DATA_CARD.md").write_text(CARD.format(version=VERSION, n=n - 1, sha=sha), encoding="utf-8")
    return f


if __name__ == "__main__":
    print(export(sys.argv[1] if len(sys.argv) > 1 else "dist/dataset"))
